-- EXAMPLE STAR-SCHEMA QUERY: TOTAL REVENUE BY MONTH AND CATEGORY
SELECT D.YEAR, D.MONTH, DP.CATEGORY, SUM(F.TOTAL_REVENUE) AS MONTHLY_REVENUE
FROM FACT_SALES F
JOIN DIM_DATE D ON F.DATE_KEY = D.DATE_KEY
JOIN DIM_PRODUCT DP ON F.PRODUCT_KEY = DP.PRODUCT_KEY
GROUP BY D.YEAR, D.MONTH, DP.CATEGORY
ORDER BY D.YEAR, D.MONTH;

