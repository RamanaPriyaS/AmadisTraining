-- SECTION 6: AGGREGATIONS & FUNCTIONS

--TOTAL PRODUCTS PER CATEGORY
SELECT CATEGORY, COUNT(*) AS TOTAL_PRODUCTS
FROM PRODUCTS
GROUP BY CATEGORY;

--TOTAL STOCK QUANTITY PER PRODUCT ACROSS ALL WAREHOUSES
SELECT PRODUCT_ID, SUM(QUANTITY_ON_HAND) AS TOTAL_STOCK
FROM INVENTORY
GROUP BY PRODUCT_ID;

--AVERAGE, MIN, MAX UNIT PRICE PER CATEGORY
SELECT CATEGORY,
AVG(UNIT_PRICE) AS AVG_PRICE,
MIN(UNIT_PRICE) AS MIN_PRICE,
MAX(UNIT_PRICE) AS MAX_PRICE
FROM PRODUCTS
GROUP BY CATEGORY;

--TOTAL SALES REVENUE PER PRODUCT, ONLY PRODUCTS WITH REVENUE > 50
SELECT PRODUCT_ID,
SUM(QUANTITY_SOLD * UNIT_PRICE) AS TOTAL_REVENUE
FROM SALES
GROUP BY PRODUCT_ID
HAVING SUM(QUANTITY_SOLD * UNIT_PRICE) > 50;

--NUMBER OF PURCHASE ORDERS AND TOTAL QUANTITY ORDERED PER SUPPLIER
SELECT SUPPLIER_ID,
COUNT(PO_ID) AS ORDER_COUNT,
SUM(QUANTITY) AS TOTAL_UNITS_ORDERED
FROM PURCHASE_ORDERS
GROUP BY SUPPLIER_ID;


-- SECTION 7: JOINS & RELATIONSHIPS

--INNER JOIN: PRODUCTS WITH THEIR SUPPLIER NAME (ONLY MATCHED ROWS)
SELECT P.PRODUCT_NAME, S.SUPPLIER_NAME
FROM PRODUCTS P
INNER JOIN SUPPLIERS S ON P.SUPPLIER_ID = S.SUPPLIER_ID;

--LEFT JOIN: ALL PRODUCTS, WITH INVENTORY IF IT EXISTS (PRODUCTS WITH NOTOCK ROW ANYWHERE STILL APPEAR, WITH NULLS)
SELECT P.PRODUCT_NAME, I.WAREHOUSE_ID, I.QUANTITY_ON_HAND
FROM PRODUCTS P
LEFT JOIN INVENTORY I ON P.PRODUCT_ID = I.PRODUCT_ID;

--RIGHT JOIN: ALL WAREHOUSES, WITH INVENTORY IF IT EXISTS USING RIGHT JOIN )
SELECT W.WAREHOUSE_NAME, I.PRODUCT_ID, I.QUANTITY_ON_HAND
FROM INVENTORY I
RIGHT JOIN WAREHOUSES W ON I.WAREHOUSE_ID = W.WAREHOUSE_ID;

--FULL OUTER JOIN: EVERY PRODUCT AND EVERY SALE, MATCHED WHERE POSSIBLE
SELECT P.PRODUCT_NAME, S.SALE_ID, S.QUANTITY_SOLD
FROM PRODUCTS P
FULL OUTER JOIN SALES S ON P.PRODUCT_ID = S.PRODUCT_ID;

--MULTI-TABLE JOIN: FULL PICTURE OF A SALE (PRODUCT, WAREHOUSE, SUPPLIER)
SELECT S.SALE_ID, P.PRODUCT_NAME, W.WAREHOUSE_NAME, SUP.SUPPLIER_NAME,
S.QUANTITY_SOLD, S.UNIT_PRICE, (S.QUANTITY_SOLD * S.UNIT_PRICE) AS LINE_TOTAL
FROM SALES S JOIN PRODUCTS P ON S.PRODUCT_ID = P.PRODUCT_ID
JOIN WAREHOUSES W ON S.WAREHOUSE_ID = W.WAREHOUSE_ID
JOIN SUPPLIERS SUP ON P.SUPPLIER_ID = SUP.SUPPLIER_ID;

-- SECTION 8: OLAP STAR SCHEMA (FACT_SALES + DIMENSIONS)

-- DIMENSION: PRODUCT (DENORMALIZED — INCLUDES CATEGORY & SUPPLIER NAME)
CREATE TABLE DIM_PRODUCT (
PRODUCT_KEY SERIAL PRIMARY KEY,
PRODUCT_ID INT NOT NULL,     
PRODUCT_NAME VARCHAR(150) NOT NULL,
CATEGORY VARCHAR(80),
SUPPLIER_NAME VARCHAR(150)
);

-- DIMENSION: WAREHOUSE
CREATE TABLE DIM_WAREHOUSE (
WAREHOUSE_KEY SERIAL PRIMARY KEY,
WAREHOUSE_ID INT NOT NULL,
WAREHOUSE_NAME VARCHAR(100) NOT NULL,
LOCATION VARCHAR(150)
);

-- DIMENSION: SUPPLIER
CREATE TABLE DIM_SUPPLIER (
SUPPLIER_KEY SERIAL PRIMARY KEY,
SUPPLIER_ID INT NOT NULL,
SUPPLIER_NAME VARCHAR(150) NOT NULL
);

-- DIMENSION: DATE 
CREATE TABLE DIM_DATE (
DATE_KEY INT PRIMARY KEY,
FULL_DATE DATE NOT NULL,
DAY INT,
MONTH INT,
QUARTER INT,
YEAR INT
);

-- FACT TABLE: ONE ROW PER SALE LINE, ONLY KEYS + ADDITIVE MEASURES
CREATE TABLE FACT_SALES (
SALE_KEY SERIAL PRIMARY KEY,
PRODUCT_KEY INT NOT NULL REFERENCES DIM_PRODUCT(PRODUCT_KEY),
WAREHOUSE_KEY INT NOT NULL REFERENCES DIM_WAREHOUSE(WAREHOUSE_KEY),
DATE_KEY INT NOT NULL REFERENCES DIM_DATE(DATE_KEY),
QUANTITY_SOLD INT NOT NULL,
UNIT_PRICE DECIMAL(10,2) NOT NULL,
TOTAL_REVENUE DECIMAL(12,2) NOT NULL
);

CREATE INDEX IDX_FACT_SALES_PRODUCT   ON FACT_SALES(PRODUCT_KEY);
CREATE INDEX IDX_FACT_SALES_WAREHOUSE ON FACT_SALES(WAREHOUSE_KEY);
CREATE INDEX IDX_FACT_SALES_DATE      ON FACT_SALES(DATE_KEY);

