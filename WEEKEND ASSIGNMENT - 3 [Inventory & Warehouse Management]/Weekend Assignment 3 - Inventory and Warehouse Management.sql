--INVENTORY & WAREHOUSE MANAGEMENT SYSTEM

--SECTION 1: CREATE DATABASE

CREATE DATABASE INVENTORY_WAREHOUSE_DB;

--SECTION 2: OLTP SCHEMA - CREATE TABLES

-- 2.1 SUPPLIERS -------------------------------------------------------------
CREATE TABLE SUPPLIERS (
SUPPLIER_ID SERIAL PRIMARY KEY,
SUPPLIER_NAME VARCHAR(150) NOT NULL,
CONTACT_NAME VARCHAR(100),
PHONE VARCHAR(20)  UNIQUE,
EMAIL VARCHAR(120) UNIQUE,
ADDRESS VARCHAR(255),
CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2.2 WAREHOUSES --------------------------------------------------------
CREATE TABLE WAREHOUSES (
WAREHOUSE_ID SERIAL PRIMARY KEY,
WAREHOUSE_NAME VARCHAR(100) NOT NULL UNIQUE,
LOCATION VARCHAR(150) NOT NULL,
CAPACITY INT CHECK (CAPACITY > 0),
CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2.3 PRODUCTS ------------------------------------------------------------
CREATE TABLE PRODUCTS (
PRODUCT_ID SERIAL PRIMARY KEY,
PRODUCT_NAME VARCHAR(150) NOT NULL,
CATEGORY VARCHAR(80),
UNIT_PRICE DECIMAL(10,2) NOT NULL CHECK (UNIT_PRICE >= 0),
REORDER_LEVEL INT NOT NULL DEFAULT 10 CHECK (REORDER_LEVEL >= 0),
SUPPLIER_ID INT NOT NULL,
CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT FK_PRODUCT_SUPPLIER
FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIERS(SUPPLIER_ID)
ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 2.4 INVENTORY (STOCK OF EACH PRODUCT AT EACH WAREHOUSE) -----------------
CREATE TABLE INVENTORY (
INVENTORY_ID SERIAL PRIMARY KEY,
PRODUCT_ID INT NOT NULL,
WAREHOUSE_ID INT NOT NULL,
QUANTITY_ON_HAND INT NOT NULL DEFAULT 0 CHECK (QUANTITY_ON_HAND >= 0),
LAST_UPDATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT FK_INV_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
CONSTRAINT FK_INV_WAREHOUSE FOREIGN KEY (WAREHOUSE_ID) REFERENCES WAREHOUSES(WAREHOUSE_ID) ON DELETE CASCADE,
CONSTRAINT UQ_PRODUCT_WAREHOUSE UNIQUE (PRODUCT_ID, WAREHOUSE_ID)  -- ONE ROW PER PRODUCT/WAREHOUSE PAIR
);

-- 2.5 PURCHASE_ORDERS (RESTOCKING FROM SUPPLIERS) --------------------------
CREATE TABLE PURCHASE_ORDERS (
PO_ID SERIAL PRIMARY KEY,
SUPPLIER_ID INT NOT NULL,
PRODUCT_ID INT NOT NULL,
WAREHOUSE_ID INT NOT NULL,
ORDER_DATE DATE NOT NULL DEFAULT CURRENT_DATE,
QUANTITY INT NOT NULL CHECK (QUANTITY > 0),
UNIT_COST DECIMAL(10,2) NOT NULL CHECK (UNIT_COST >= 0),
STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (STATUS IN ('PENDING','RECEIVED','CANCELLED')),
CONSTRAINT FK_PO_SUPPLIER FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIERS(SUPPLIER_ID),
CONSTRAINT FK_PO_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
CONSTRAINT FK_PO_WAREHOUSE FOREIGN KEY (WAREHOUSE_ID) REFERENCES WAREHOUSES(WAREHOUSE_ID)
);

-- 2.6 SALES -----------------------------------------------------------------
CREATE TABLE SALES (
SALE_ID SERIAL PRIMARY KEY,
PRODUCT_ID INT NOT NULL,
WAREHOUSE_ID INT NOT NULL,
SALE_DATE DATE NOT NULL DEFAULT CURRENT_DATE,
QUANTITY_SOLD INT NOT NULL CHECK (QUANTITY_SOLD > 0),
UNIT_PRICE DECIMAL(10,2) NOT NULL CHECK (UNIT_PRICE >= 0),
CONSTRAINT FK_SALE_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
CONSTRAINT FK_SALE_WAREHOUSE FOREIGN KEY (WAREHOUSE_ID) REFERENCES WAREHOUSES(WAREHOUSE_ID)
);

-- 2.7 STOCK_MOVEMENTS (AUDIT TRAIL: IN / OUT / TRANSFER) --------------------
CREATE TABLE STOCK_MOVEMENTS (
MOVEMENT_ID SERIAL PRIMARY KEY,
PRODUCT_ID INT NOT NULL,
WAREHOUSE_ID INT NOT NULL,
MOVEMENT_TYPE VARCHAR(10) NOT NULL CHECK (MOVEMENT_TYPE IN ('IN','OUT','TRANSFER')),
QUANTITY INT NOT NULL CHECK (QUANTITY > 0),
MOVEMENT_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
REFERENCE_TYPE VARCHAR(20),
REFERENCE_ID INT,
CONSTRAINT FK_MOV_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
CONSTRAINT FK_MOV_WAREHOUSE FOREIGN KEY (WAREHOUSE_ID) REFERENCES WAREHOUSES(WAREHOUSE_ID)
);


--SECTION 3: INDEXING

CREATE INDEX IDX_PRODUCTS_SUPPLIER ON PRODUCTS(SUPPLIER_ID);
CREATE INDEX IDX_PRODUCTS_CATEGORY ON PRODUCTS(CATEGORY);
CREATE INDEX IDX_INVENTORY_PRODUCT ON INVENTORY(PRODUCT_ID);
CREATE INDEX IDX_INVENTORY_WAREHOUSE ON INVENTORY(WAREHOUSE_ID);
CREATE INDEX IDX_PO_PRODUCT ON PURCHASE_ORDERS(PRODUCT_ID);
CREATE INDEX IDX_PO_SUPPLIER ON PURCHASE_ORDERS(SUPPLIER_ID);
CREATE INDEX IDX_PO_ORDER_DATE ON PURCHASE_ORDERS(ORDER_DATE);
CREATE INDEX IDX_SALES_PRODUCT ON SALES(PRODUCT_ID);
CREATE INDEX IDX_SALES_WAREHOUSE ON SALES(WAREHOUSE_ID);
CREATE INDEX IDX_SALES_DATE ON SALES(SALE_DATE);
CREATE INDEX IDX_MOVEMENTS_PRODUCT ON STOCK_MOVEMENTS(PRODUCT_ID);
CREATE INDEX IDX_MOVEMENTS_DATE ON STOCK_MOVEMENTS(MOVEMENT_DATE);

