-- SECTION 9 : REAL-TIME QUERIES

-- LIST PRODUCTS WITH STOCK BELOW THE REORDER LEVEL
SELECT P.PRODUCT_ID,
P.PRODUCT_NAME,
COALESCE(SUM(I.QUANTITY_ON_HAND), 0) AS TOTAL_STOCK,
P.REORDER_LEVEL
FROM PRODUCTS P
LEFT JOIN INVENTORY I ON P.PRODUCT_ID = I.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME, P.REORDER_LEVEL
HAVING COALESCE(SUM(I.QUANTITY_ON_HAND), 0) < P.REORDER_LEVEL
ORDER BY TOTAL_STOCK ASC;

-- FIND SUPPLIERS PROVIDING MORE THAN 20 PRODUCTS
SELECT S.SUPPLIER_ID,
S.SUPPLIER_NAME,
COUNT(P.PRODUCT_ID) AS PRODUCT_COUNT
FROM SUPPLIERS S
JOIN PRODUCTS P ON S.SUPPLIER_ID = P.SUPPLIER_ID
GROUP BY S.SUPPLIER_ID, S.SUPPLIER_NAME
HAVING COUNT(P.PRODUCT_ID) > 20;

-- CALCULATE WAREHOUSE-WISE INVENTORY VALUE (QTY * UNIT_PRICE)
SELECT W.WAREHOUSE_ID,
W.WAREHOUSE_NAME,
SUM(I.QUANTITY_ON_HAND * P.UNIT_PRICE) AS INVENTORY_VALUE
FROM WAREHOUSES W
JOIN INVENTORY I ON W.WAREHOUSE_ID = I.WAREHOUSE_ID
JOIN PRODUCTS P ON I.PRODUCT_ID = P.PRODUCT_ID
GROUP BY W.WAREHOUSE_ID, W.WAREHOUSE_NAME
ORDER BY INVENTORY_VALUE DESC;

--DISPLAY PRODUCTS THAT HAVEN'T BEEN SOLD IN THE LAST 6 MONTHS
SELECT P.PRODUCT_ID, P.PRODUCT_NAME, P.CATEGORY
FROM PRODUCTS P
WHERE NOT EXISTS (
SELECT 1 FROM SALES S WHERE S.PRODUCT_ID = P.PRODUCT_ID
AND S.SALE_DATE >= CURRENT_DATE - INTERVAL '6 MONTHS')
ORDER BY P.PRODUCT_NAME;


