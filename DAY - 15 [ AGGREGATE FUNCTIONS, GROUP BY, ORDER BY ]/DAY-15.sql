--GROUP BY--------------------------------------------------------------------------------------------------------------------------------------
--SALE IN EACH CITY
SELECT CITY,COUNT(*) FROM SALES GROUP BY CITY;

--QUANTITY SOLD PER CATEGORY
SELECT CATEGORY,SUM(QUANTITY) FROM SALES GROUP BY CATEGORY;

--AVERAGE PRICE PER CATEGORY
SELECT CATEGORY, AVG(PRICE) FROM SALES GROUP BY CATEGORY;

--MAX PRICE FOR EACH PRODUCT
SELECT PRODUCT,MAX(PRICE) FROM SALES GROUP BY PRODUCT;

--MINIMUM QUANTITY FOR EACH CITY
SELECT CITY,MIN(QUANTITY) FROM SALES GROUP BY CITY;

--ORDER BY--------------------------------------------------------------------------------------------------------------------------------------
--TOTAL REVENUE PER CATEGORY ORDERED FROM GIGHEST REVENUE
SELECT CATEGORY,SUM(MULTIPLY_NUMBERS(PRICE,QUANTITY)) AS REVENUE FROM SALES GROUP BY CATEGORY ORDER BY REVENUE DESC;

--AVERAGE QUANTITY BY CITY IN DESCENDING ORDER
SELECT CITY,AVG(QUANTITY) AS AVG_QUANTITY FROM SALES GROUP BY CITY ORDER BY AVG_QUANTITY;

--COUNT OF PRODUCT SOLD ORDERED ALPHABETICALLY
SELECT PRODUCT,SUM(QUANTITY) AS SOLD FROM SALES GROUP BY PRODUCT ORDER BY PRODUCT;

--WHERE VS HAVING --------------------------------------------------------------------------------------------------------------------------------------
--AVERAGE PRICE OF ELECTRONICS ONLY - WHERE
SELECT AVG(PRICE) AS AVG_ELECTRONICS_PRICE FROM SALES WHERE CATEGORY='Electronics';

--CITIES WHOES QUANTITY EXCEED 10
SELECT CITY,SUM(QUANTITY) AS TOTAL_QUANTITY FROM SALES GROUP BY CITY HAVING SUM(QUANTITY)>10;

--CATEGORIES WHOES AVERAGE PRICE EXCEEDS 10000
SELECT CATEGORY,AVG(PRICE) AS AVERAGE FROM SALES GROUP BY CATEGORY HAVING AVG(PRICE)>10000;

--PRODUCTS HAVING MORE THAN 2 SALES
SELECT PRODUCT,COUNT(PRODUCT) FROM SALES GROUP BY PRODUCT HAVING COUNT(PRODUCT)>2;

--HAVING WITHOUT GROUP BY--------------------------------------------------------------------------------------------------------------------------------------
--TOTAL SALE ONLY IF TOTAL REVENUE EXCEEDS 500000
SELECT SUM(MULTIPLY_NUMBERS(PRICE,QUANTITY)) FROM SALES HAVING SUM(MULTIPLY_NUMBERS(PRICE,QUANTITY))>500000;

--AVERAGE PRICE ONLY IF AVERAGE PRICE EXCEEDS 10000
SELECT AVG(PRICE) FROM SALES HAVING AVG(PRICE)>10000;

--TOTAL QUANTITY IF TOTAL QUANTITY EXCEEDS 40
SELECT SUM(QUANTITY) FROM SALES HAVING SUM(QUANTITY)>40;

--FILTER CLAUSE--------------------------------------------------------------------------------------------------------------------------------------
--TOTAL ELECTRONICS REVENUE
SELECT SUM(MULTIPLY_NUMBERS(PRICE,QUANTITY)) FILTER (WHERE CATEGORY='Electronics') AS ELECTRONIC_REVENUE FROM SALES ;

--COUNT FURNITURE ORDERS
SELECT COUNT(PRODUCT) FILTER (WHERE CATEGORY='Furniture') FROM SALES;

--AVERAGE LAPTOP PRICE
SELECT AVG(PRICE) FILTER (WHERE PRODUCT='Laptop') FROM SALES;

--SUM OF QUANTITY FOR ELECTRONICS AND FURNITURE
