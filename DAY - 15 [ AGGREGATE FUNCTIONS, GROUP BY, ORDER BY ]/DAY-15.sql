--FUNCTION--------------------------------------------------------------------------------------------------------------------------------------
--DEFINE A FUNC FOR MULTIPLICATION
CREATE OR REPLACE FUNCTION MULTIPLY_NUMBERS(price NUMERIC,quantity INT)
RETURNS NUMERIC AS
$$
BEGIN
	RETURN quantity * price;
END;
$$
LANGUAGE plpgsql;

