--MODE()--------------------------------------------------------------------------------------------------------------------------------------
--MODE OF QUANTIITY
SELECT MODE() WITHIN GROUP(ORDER BY QUANTITY) AS FREQ_QUANTITY FROM SALES;

--MODE OF PRICE
SELECT MODE() WITHIN GROUP(ORDER BY PRICE) AS FREQ_PRICE FROM SALES;

--MODE OF CATEGORY 
SELECT MODE() WITHIN GROUP(ORDER BY CATEGORY) AS FREQ_CATEGORY FROM SALES;

--WINDOW FUNCTIOM------------------------------------------------------------------------------------------------------------------------------
--SHOW EVERY ROW WITH TOTAL SALES ACROSS ALL ROWS
SELECT CUSTOMER_NAME, PRICE*QUANTITY AS REVENUE, SUM(PRICE*QUANTITY) OVER() AS TOTAL_REVENUE FROM SALES;

--EACH SALE WITH AVERAGE PRICE FOR ITS CITY
SELECT CUSTOMER_NMAE,CITY,QUANTITY,SUM(QUANTITY) OVER(PARTITION BY CITY) AS CITY_TOTAL_QUANTITY FROM SALES;

--ASSIGN ROW NUMBER WITHON EACH CITY 
SELECT CITY,CUSTOMER_NAME,ROW_NUMBER() OVER(PARTITION BY CITY ORDER BY SALE_DATE) AS ROW_NO FROM SALES;

--RANK BY PRICE
SELECT PRODUCT,PRICE,RANK() OVER(ORDER BY PRICE DESC) AS RANK FROM SALES;

--PRODUCT WITH CATEGORY
SELECT CATEGORY,PRODUCT,PRICE,RANK() OVER(PARTITION BY CATEGORY ORDER BY PRICE DESC) AS RANK FROM SALES;

--DENSE RANK PRODUCT WITHIN CATEGORY
SELECT  CATEGORY,PRODUCT,PRICE,DENSE_RANK() OVER(PARTITION BY CATEGORY ORDER BY PRICE DESC) AS DENSE_RANK FROM SALES;


