--STRING_AGG()--------------------------------------------------------------------------------------------------------------------------------------
--LIST ALL CUSTOMER NAME SEPERATED BY COMMAS
SELECT STRING_AGG(CUSTOMER_NAME,',') AS CUSTOMERS FROM SALES; 

--LIST ALL PRODUCT IN EACH CATEGORY
SELECT CATEGORY,STRING_AGG(PRODUCT,',') FROM SALES GROUP BY CATEGORY;

--CITIES ALPHABETICALLY SEPERATED BY |
SELECT STRING_AGG(DISTINCT CITY,'|') AS CITIES FROM SALES ;

--LIST DISTINCT PRODUCT
SELECT STRING_AGG(DISTINCT PRODUCT,'|') AS PRODUCTS FROM SALES

